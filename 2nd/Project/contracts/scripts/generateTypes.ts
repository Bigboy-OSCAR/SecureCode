/**
 * Generates contracts/generated/ts/contracts.ts from every *.schema.json.
 * All definitions are compiled from one synthetic root so a type referenced by
 * several files is declared once. `--check` fails when the file is stale.
 *
 * Usage: npm run generate -w @securecode/contracts [-- --check]
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compile, type JSONSchema } from "json-schema-to-typescript";
import { format, resolveConfig } from "prettier";
import { loadSchemaFiles, resolveContractsRoot } from "../src/schemaFiles.js";

const BANNER = [
    "/* eslint-disable */",
    "/**",
    " * GENERATED by contracts/scripts/generateTypes.ts from the contracts JSON Schema files.",
    " * Do not edit by hand: change the schema and run `npm run generate:contracts`.",
    " */",
].join("\n");

function buildRootSchema(contractsRoot: string): JSONSchema {
    const properties: Record<string, JSONSchema> = {};
    for (const file of loadSchemaFiles(contractsRoot)) {
        const definitions = (file.schema.definitions ?? {}) as Record<string, JSONSchema>;
        for (const definitionName of Object.keys(definitions)) {
            if (definitionName in properties) {
                throw new Error(`duplicate definition name across schemas: ${definitionName} (${file.relativePath})`);
            }
            properties[definitionName] = { $ref: `${file.relativePath}#/definitions/${definitionName}` };
        }
    }
    return {
        title: "ContractsIndex",
        description: "Synthetic root that pulls every contract definition into one generated module.",
        type: "object",
        additionalProperties: false,
        properties,
    };
}

async function generate(contractsRoot: string): Promise<string> {
    const rootSchema = buildRootSchema(contractsRoot);
    const compiled = await compile(rootSchema, "ContractsIndex", {
        cwd: contractsRoot,
        bannerComment: BANNER,
        additionalProperties: false,
        strictIndexSignatures: true,
        unknownAny: true,
        format: false,
        maxItems: -1,
    });
    const prettierConfig = (await resolveConfig(join(contractsRoot, "generated", "ts", "contracts.ts"))) ?? {};
    return format(compiled, { ...prettierConfig, parser: "typescript" });
}

async function main(): Promise<void> {
    const contractsRoot = resolveContractsRoot();
    const outputPath = join(contractsRoot, "generated", "ts", "contracts.ts");
    const generated = await generate(contractsRoot);

    if (process.argv.includes("--check")) {
        let current: string;
        try {
            current = readFileSync(outputPath, "utf8");
        } catch {
            current = "";
        }
        if (current !== generated) {
            console.error("FAIL contracts/generated/ts/contracts.ts is stale. Run `npm run generate:contracts`.");
            process.exitCode = 1;
            return;
        }
        console.log("PASS generated contract types are up to date");
        return;
    }

    mkdirSync(join(contractsRoot, "generated", "ts"), { recursive: true });
    writeFileSync(outputPath, generated, "utf8");
    console.log("wrote contracts/generated/ts/contracts.ts");
}

await main();
